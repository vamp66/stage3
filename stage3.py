#here I imported all modules I used and my CNN model files for each dataset
import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import precision_score, recall_score, f1_score
from script_data_loader import data
from Method_CNN_MNIST import Method_CNN_MNIST
from Method_CNN_CIFAR import Method_CNN_CIFAR
from Method_CNN_ORL import Method_CNN_ORL
from Evaluate_Accuracy import Evaluate_Accuracy


#this trains and evals the cnn with the test data
def cnn(name, cnnUsed):
    print(name)
    #this gets the training images & labels
    X_train = []
    y_train = []
    i = 0
    while i < len(data['train']):
        X_train.append(data['train'][i]['image'])
        y_train.append(data['train'][i]['label'])
        i += 1
    #this gets the test images & labels
    X_test = []
    y_test = []
    i = 0
    while i < len(data['test']):
        X_test.append(data['test'][i]['image'])
        y_test.append(data['test'][i]['label'])
        i += 1
    #preps the data
    X_train = np.array(X_train)
    y_train = np.array(y_train)
    X_test = np.array(X_test)
    y_test = np.array(y_test)
    #this makes & runs the cnn based on my imported dataset specific files using its cnn class
    cnn = cnnUsed('cnn', '')
    cnn.data = {
        'train': {'X': X_train, 'y': y_train},
        'test': {'X': X_test, 'y': y_test}}
    result = cnn.run()
    #gets predicted and actual testing labels
    pred_y = result['pred_y'].numpy()
    true_y = np.array(result['true_y'])
    #calcs testing accuracy using given evaluate_accuracy.py
    accuracy_evaluator = Evaluate_Accuracy('testing evaluator', '')
    accuracy_evaluator.data = {
        'true_y': true_y,
        'pred_y': pred_y}
    print('Testing accuracy:', accuracy_evaluator.evaluate())
    #here I calculated precision, recall, and F1 scores
    averages = ['macro', 'weighted', 'micro']
    i = 0
    while i < len(averages):
        avg = averages[i]
        print(avg, 'precision:', precision_score(true_y, pred_y, average=avg))
        print(avg, 'recall:', recall_score(true_y, pred_y, average=avg))
        print(avg, 'f1:', f1_score(true_y, pred_y, average=avg))
        i += 1
    #this plots the training loss curve
    plt.plot(range(1, len(cnn.loss_list) + 1), cnn.loss_list)
    plt.xlabel('Epoch')
    plt.ylabel('Training Loss')
    plt.title('Learning Curve')
    plt.savefig('Learning_Curve.png')
    plt.close()


#runs the CNN using the dataset selected in data_loader.py (the one chosen needs to be changed to 1); NOTE: change the second argument to the corresponding program like Method_CNN_ORL for ORL and such and the first argument to print its corresponding dataset name for clarity
cnn('MNIST', Method_CNN_MNIST)


